type Seed = [word: string, emoji: string, difficulty: SpeechCard['difficulty']]

function build(prefix: string, category: string, color: string, seeds: Seed[]): SpeechCard[] {
  return seeds.map(([word, imageEmoji, difficulty], i) => ({
    id: `${prefix}-${i + 1}`,
    word,
    category,
    categoryColor: color,
    imageEmoji,
    difficulty,
    stars: difficulty === 'easy' ? 5 : difficulty === 'medium' ? 10 : 15,
  }))
}

